public class TypeCasting {

    public static void main(String[] args) {
        
        // automatically conversion
        int a =5;
        double d = a;
        System.out.println(a);
        System.out.println(d);

        // forcefully conversion

        double d1 = 67.987d;
        int myint = (int)d1;
        System.out.println(d1);
        System.out.println(myint);


    }
    
}
